function Get-VcEnv($arch) {
    $envs = @{}
    cmd /c "`"$vs\VC\Auxiliary\Build\vcvarsall.bat`" $arch >nul && set" | ForEach-Object {
        if ($_ -match '^([^=]+)=(.*)$') { $envs[$Matches[1]] = $Matches[2] }
    }
    if (-not $envs.Count) { throw "vcvarsall $arch failed" }
    $envs
}
# Runs $body with the compiler environment of $vcArch (vcvarsall argument), then
# restores this process's. $body runs in this function's scope: no names here
# may shadow the caller's variables.
function Use-VcEnv($vcArch, [scriptblock]$body) {
    $saved = [Environment]::GetEnvironmentVariables()
    foreach ($kv in (Get-VcEnv $vcArch).GetEnumerator()) { [Environment]::SetEnvironmentVariable($kv.Key, $kv.Value) }
    try {
        . $body
    } finally {
        foreach ($k in [Environment]::GetEnvironmentVariables().Keys) {
            if (-not $saved.Contains($k)) { [Environment]::SetEnvironmentVariable($k, $null) }
        }
        foreach ($kv in $saved.GetEnumerator()) { [Environment]::SetEnvironmentVariable($kv.Key, $kv.Value) }
    }
}
