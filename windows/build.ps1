function Read-Env($path) {
    $vars = @{}
    foreach ($line in [IO.File]::ReadAllLines($path, [Text.Encoding]::UTF8)) {
        if ($line -match '^\s*([A-Z_]+)="(.*)"\s*$') { $vars[$Matches[1]] = $Matches[2] }
    }
    $vars
}

