            "/PDB:$obj\MaimusiTIP.pdb" "/IMPLIB:$obj\MaimusiTIP.lib" $objs $res $coreLib @tipLibs
        if ($LASTEXITCODE) { throw 'link failed' }

        if ($arch.dir -eq 'x64') {
            Write-Host '== settings'
            $sobj = "$Out\obj\settings"
