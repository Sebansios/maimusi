# Both return the path of what they built (tool output goes to the console).
function Build-Core($target) {
    & cargo build --quiet --release --offline --lib --manifest-path "$Root\core\Cargo.toml" --target $target | Out-Host
    if ($LASTEXITCODE) { throw "cargo build failed ($target)" }
    "$Root\core\target\$target\release\hangul_core.lib"
}
function Build-TipResource($obj) {
    Copy-Item "$Gen\Maimusi.ico" $obj
    & rc.exe /nologo /I $Gen /fo "$obj\MaimusiTIP.res" "$Gen\MaimusiTIP.dll.rc" | Out-Host
    if ($LASTEXITCODE) { throw 'rc failed' }
    "$obj\MaimusiTIP.res"
}

