        }
    }
}

# --- ARM64X text service (Windows 11 on Arm). ARM64 applications and x64
# applications under emulation read the same 64-bit InprocServer32 path, so one
# DLL serves both: ARM64 code for the former, ARM64EC code (native, x64 calling
# convention) for the latter. 32-bit applications use x86\ as on x64 Windows.
Write-Host '== core (arm64, arm64ec)'
$coreArm64 = Build-Core 'aarch64-pc-windows-msvc'
$coreArm64ec = Build-Core 'arm64ec-pc-windows-msvc'
Write-Host '== text service (arm64x)'
$obj = "$Out\obj\arm64"
$objEc = "$Out\obj\arm64ec"
New-Item -ItemType Directory -Force $obj, $objEc, "$Stage\arm64" | Out-Null
Use-VcEnv 'x64_arm64' {
    & cl.exe @common /c "/Fo$obj\\" $tipSources
    if ($LASTEXITCODE) { throw 'compile failed (arm64)' }
    & cl.exe @common /arm64EC /c "/Fo$objEc\\" $tipSources
    if ($LASTEXITCODE) { throw 'compile failed (arm64ec)' }
    $res = Build-TipResource $obj
    $objs = Get-ChildItem "$obj\*.obj", "$objEc\*.obj" | ForEach-Object FullName
    # LNK4279 on SetFilePointerEx is harmless: Rust std and the UCRT describe its
    # LARGE_INTEGER argument as i8 and m8, both passed in one integer register.
    & link.exe @linkCommon /DLL /MACHINE:ARM64X "/DEF:$tipDef" "/DEFARM64NATIVE:$tipDef" `
        "/OUT:$Stage\arm64\MaimusiTIP.dll" "/PDB:$obj\MaimusiTIP.pdb" "/IMPLIB:$obj\MaimusiTIP.lib" `
        $objs $res $coreArm64 $coreArm64ec @tipLibs
    if ($LASTEXITCODE) { throw 'link failed (arm64x)' }
}

