#!/usr/bin/env python3
"""Cross-platform version source: python tools/versions.py check|sync|get FIELD."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]


def load(root=ROOT):
    data = json.loads((root / 'versions.json').read_text(encoding='utf-8'))
    if data.get('schema') != 1:
        raise ValueError('unsupported version schema')
    for key in ('product', 'engine'):
        if not re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)', data[key]):
            raise ValueError(f'invalid {key} version')
    if type(data['build']) is not int or data['build'] < 1:
        raise ValueError('build must be a positive integer')
    for key in ('release_label', 'release_suffix'):
        if not re.fullmatch(r'[A-Za-z0-9 .-]*', data[key]):
            raise ValueError(f'invalid {key}')
    if bool(data['release_label']) != bool(data['release_suffix']):
        raise ValueError('release label and suffix must both be empty or set')
    return data


def outputs(root, data):
    result = {}
    for name in ('core/Cargo.toml', 'core/Cargo.lock'):
        text = (root / name).read_text(encoding='utf-8')
        text, count = re.subn(r'(name = "hangul-core"\nversion = ")[^"]+',
                              lambda m: m[1] + data['product'], text, count=1)
        if count != 1:
            raise ValueError(f'missing hangul-core version: {name}')
        result[name] = text
    result['engine/hangul_ime/_version.py'] = (
        '# Generated by tools/versions.py; edit versions.json.\n'
        f'PRODUCT_VERSION = "{data["product"]}"\n'
        f'ENGINE_VERSION = "{data["engine"]}"\n')
    result['packaging/version.env'] = (
        '# Generated by tools/versions.py; edit versions.json.\n'
        + ''.join(f'{key}="{data[field]}"\n' for key, field in (
            ('VERSION', 'product'), ('ENGINE_VERSION', 'engine'),
            ('VERSION_BUILD', 'build'), ('RELEASE_LABEL', 'release_label'),
            ('RELEASE_FILE_SUFFIX', 'release_suffix'))))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['check', 'sync', 'get'])
    parser.add_argument('field', nargs='?')
    args = parser.parse_args()
    data = load()
    if args.command == 'get':
        if args.field not in data:
            parser.error('unknown version field')
        print(data[args.field])
        return
    stale = []
    for name, expected in outputs(ROOT, data).items():
        path = ROOT / name
        if not path.exists() or path.read_text(encoding='utf-8') != expected:
            stale.append(name)
            if args.command == 'sync':
                path.write_text(expected, encoding='utf-8', newline='\n')
    if stale and args.command == 'check':
        print('Version mismatch; run python tools/versions.py sync: ' + ', '.join(stale), file=sys.stderr)
        sys.exit(1)
    print(f'Maimusi {data["product"]} / CharTec {data["engine"]} / build {data["build"]}: {args.command} OK')


if __name__ == '__main__':
    main()
